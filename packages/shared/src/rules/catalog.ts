const BY_ID: ReadonlyMap<string, RuleCatalogEntry> = new Map(ENTRIES.map((entry) => [entry.id, entry]));

export function listRules(): readonly RuleCatalogEntry[] {
  return ENTRIES;
}

export function getRule(id: string): RuleCatalogEntry | undefined {
  return BY_ID.get(id);
}

export function isKnownRuleId(id: string): boolean {
  return BY_ID.has(id);
}

export function listRulesByCategory(category: RuleCategory): readonly RuleCatalogEntry[] {
  return ENTRIES.filter((entry) => entry.category === category);
}

export function listRulesByStatus(status: RuleStatus): readonly RuleCatalogEntry[] {
  return ENTRIES.filter((entry) => entry.status === status);
}

export function isRuleCategory(value: unknown): value is RuleCategory {
  return typeof value === 'string' && (RULE_CATEGORIES as readonly string[]).includes(value);
}
