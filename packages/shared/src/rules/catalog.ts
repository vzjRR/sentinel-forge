/**
 * Rule catalog.
 *
 * Rule identifiers are a public contract: they appear in reports, in CI
 * failure conditions, and in user configuration. An identifier's meaning must
 * never change silently (see docs/RELEASE.md § Rule stability).
 *
 * A catalog entry declares intent and ownership; the executable rule lives in
 * the package named by `implementedIn`. `status` states honestly whether the
 * rule is implemented in this build.
 */

import type { Severity } from '../severity.js';

export const RULE_CATEGORIES = [
  'PERFORMANCE',
  'DEPENDENCIES',
  'SECURITY',
  'INTEGRITY',
  'CONFIGURATION',
  'ERRORS',
] as const;

export type RuleCategory = (typeof RULE_CATEGORIES)[number];

export type RuleStatus = 'IMPLEMENTED' | 'NOT_IMPLEMENTED';

/** Development gate that owns delivery of a rule (see docs/GATE_STATUS.md). */
export type GateNumber = 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8;

export interface RuleCatalogEntry {
  readonly id: string;
  readonly category: RuleCategory;
  /** Severity the rule emits by default; individual findings may lower it with reason. */
  readonly defaultSeverity: Severity;
  readonly title: string;
  /** What the rule looks for. */
  readonly description: string;
  /** Why the finding matters to a server operator. */
  readonly rationale: string;
  /** Known conditions under which this rule can report a benign pattern. */
  readonly falsePositives: readonly string[];
  /** Evidence the rule must attach before emitting a finding. */
  readonly evidenceRequirements: readonly string[];
  readonly status: RuleStatus;
  readonly targetGate: GateNumber;
  /** Workspace package that implements (or will implement) the rule. */
  readonly implementedIn: string;
}

